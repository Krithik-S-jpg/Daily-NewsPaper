import {PGlite} from '../../frontend/node_modules/@electric-sql/pglite/dist/index.js';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
const one='00000000-0000-4000-8000-000000000001';
const two='00000000-0000-4000-8000-000000000002';
await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
create schema auth; create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;
insert into auth.users values('${one}'),('${two}');`);
for(const name of ['001_initial.sql','002_transactions.sql','003_request_limits.sql','004_reading_progress.sql'])await db.exec(await readFile(new URL(`../migrations/${name}`,import.meta.url),'utf8'));
await db.exec('grant usage on schema public to authenticated; grant select,insert,update,delete on all tables in schema public to authenticated;');
const prefs={topics:['Science','Custom interest'],time:'07:00',timezone:'Asia/Kolkata',days:[0,1,2,3,4,5,6],email:false};
await db.query('select save_preferences($1,$2,$3)',[one,JSON.stringify(prefs),'2026-10-22T01:30:00Z']);
assert.equal((await db.query('select * from user_topics')).rows.length,2);
const first=(await db.query('select (enqueue_manual($1)).*',[one])).rows[0];
const retry=(await db.query('select (enqueue_manual($1)).*',[one])).rows[0];
assert.equal(first.id,retry.id,'manual active job deduplication');
const claimed=(await db.query('select * from claim_job()')).rows[0];
assert.equal((await db.query('select * from claim_job()')).rows.length,0,'leased work is not claimed twice');
const articleId='00000000-0000-4000-8000-000000000010';
const content={id:claimed.edition_id,date:'2026-10-21',title:'Fixture',articles:[{id:articleId,headline:'Attributed fixture',summary:'Source evidence',category:'Science',source:'Fixture',url:'https://example.com/story',published_at:null}]};
for(let i=0;i<2;i++)await db.query('select publish_edition($1,$2,$3,$4)',[claimed.id,claimed.lease_token,JSON.stringify(content),'Asia/Kolkata']);
assert.equal((await db.query('select * from editions')).rows.length,1,'immutable edition retry');
assert.equal((await db.query('select * from articles')).rows.length,1,'article retry');
assert.equal((await db.query('select * from delivery_logs')).rows.length,1,'delivery retry');
await db.query('insert into reading_progress(user_id,edition_id,mode,page) values($1,$2,$3,$4)',[one,claimed.edition_id,'spread',4]);
await assert.rejects(db.query('insert into reading_progress(user_id,edition_id,mode,page) values($1,$2,$3,$4)',[two,claimed.edition_id,'spread',4]),'foreign edition progress rejected');
await db.query('select enqueue_scheduled($1,$2,$3)',[one,'2026-10-22T01:30:00Z','2026-10-23T01:30:00Z']);
await db.query('select enqueue_scheduled($1,$2,$3)',[one,'2026-10-22T01:30:00Z','2026-10-23T01:30:00Z']);
assert.equal((await db.query('select * from generation_jobs')).rows.length,2,'scheduled run deduplication');
assert.equal((await db.query('select consume_budget($1,$2,$3) as allowed',[one,'test',1])).rows[0].allowed,true);
assert.equal((await db.query('select consume_budget($1,$2,$3) as allowed',[one,'test',1])).rows[0].allowed,false);
await db.exec(`set role authenticated; set request.jwt.claim.sub='${two}';`);
for(const table of ['profiles','editions','articles','delivery_logs','generation_jobs','connected_sources','user_topics','source_items','reading_progress'])assert.equal((await db.query(`select * from ${table}`)).rows.length,0,`${table}: other account cannot read`);
await assert.rejects(db.query('insert into profiles(user_id) values($1)',[two]),'browser cannot bypass server mutation checks');
await assert.rejects(db.query('select * from claim_job()'),'browser cannot claim jobs');
await assert.rejects(db.query('select enqueue_manual($1)',[two]),'browser cannot enqueue directly');
await db.exec(`set request.jwt.claim.sub='${one}';`);
assert.equal((await db.query('select * from editions')).rows.length,1,'owner can read');
assert.equal((await db.query('select * from reading_progress')).rows[0].page,4,'owner can resume');
await db.query('update reading_progress set page=7');
assert.equal((await db.query('select * from reading_progress')).rows[0].page,4,'browser cannot mutate progress directly');
await db.exec('reset role;');
await assert.rejects(db.query('insert into user_bookmarks(user_id,article_id) values($1,$2)',[two,articleId]),'cross-user bookmark FK');
await db.query('delete from auth.users where id=$1',[one]);
assert.equal((await db.query('select * from editions')).rows.length,0,'account deletion cascades');
assert.equal((await db.query('select * from reading_progress')).rows.length,0,'progress deletion cascades');
await db.close();
console.log('PostgreSQL checks passed: migrations, RLS isolation, owner reads, restricted RPCs, atomic preferences, job leases, idempotent publishing/scheduling, rate limits, and deletion cascades.');
